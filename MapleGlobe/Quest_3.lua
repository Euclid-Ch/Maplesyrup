function Quest_3.showShaolinChiefPriestCutsceneToClient(self, duration)
  local player = ___MOD._UserService.LocalPlayer
  local ui = ___MOD._EntityService:GetEntityByPath("/ui/UIGroup")
  if not (___MOD.isvalid(player) and ___MOD.isvalid(ui)) or duration <= 0 then
    return
  end
  local animation = ___MOD._EffectManager:getEffect("EffectCN.img/shaolin/CutScean")
  if animation == nil then
    return
  end
  local pool = ui.UIPool.UIEffectPool
  local effectEntity = ___MOD._ObjectPool:pick(pool, "Effect", "model://6e36bd76-88aa-4315-b583-986d769f06b2", ___MOD.FastVector3.zero:Clone(), ui, true)
  if ___MOD.isvalid(effectEntity.UITransformComponent) then
    ___MOD._UILogic:SetSiblingIndex(effectEntity.UITransformComponent, 999)
  end
  local animationSprite = effectEntity.AnimationSpriteComponent
  animationSprite:setWzSprite(animation, false)
  animationSprite.loop = false
  animationSprite.disappearWhenAnimationOnceEnd = false
  animationSprite.releasePool = pool
  ___MOD._TimerService:SetTimerOnce(function()
    if ___MOD.isvalid(effectEntity) then
      ___MOD._ObjectPool:release(pool, effectEntity, true)
    end
  end, duration)
end

