function Portal_1.playSecretLibraryDirectionToClient(self)
  local user = ___MOD._UserService.LocalPlayer
  local map = ___MOD.isvalid(user) and user.CurrentMap or nil
  if not ___MOD.isvalid(map) or map.MapInfoComponent.mapID ~= 701220352 then
    return
  end
  local direction = ___MOD._EffectManager:getDirection("Effect/Direction_CN.img/shaolinDirection/SecretLibrary")
  if direction == nil then
    return
  end
  local keys = {}
  for key, _ in ___MOD.pairs(direction) do
    if ___MOD.tonumber(key) ~= nil then
      ___MOD.table.insert(keys, key)
    end
  end
  ___MOD.table.sort(keys, function(a, b)
    return ___MOD.tonumber(a) < ___MOD.tonumber(b)
  end)
  local lastKey = keys[#keys]
  for _, key in ___MOD.ipairs(keys) do
    local imageMove = direction[key]
    if imageMove.type == ___MOD._EffectDirectionType.imageMove then
      local visual = imageMove.visual
      visual, _ = visual:gsub("^Effect/", "")
      local animation = ___MOD._EffectManager:getEffect(visual .. "/0")
      if animation == nil or animation.anim == nil or animation.anim[1] == nil then
        animation = ___MOD._EffectManager:getEffect(visual)
      end
      if animation ~= nil and animation.anim ~= nil and animation.anim[1] ~= nil then
        local x = imageMove.x / 100
        local y = -(imageMove.y / 100)
        local start = imageMove.start / 1000
        local isLastEffect = key == lastKey
        ___MOD._TimerService:SetTimerOnce(function()
          if not ___MOD.isvalid(user) or user.CurrentMap ~= map then
            return
          end
          local effectEntity = ___MOD._SpawnService:SpawnByModelId("model://f4bb0e1c-f068-4fcb-ab5c-c53e53d72928", "direction", ___MOD.FastVector3(x, y, 0), map)
          effectEntity.TransformComponent.Scale = ___MOD.FastVector3(0.5, 0.5, 1)
          local animationSprite = effectEntity.AnimationSpriteComponent
          animationSprite:setOrderInLayer(imageMove.z)
          animationSprite.loop = false
          animationSprite.disappearWhenAnimationOnceEnd = true
          if isLastEffect then
            local completionTimer
            completionTimer = ___MOD._TimerService:SetTimerRepeat(function()
              if not ___MOD.isvalid(user) or user.CurrentMap ~= map or not ___MOD.isvalid(animationSprite) then
                ___MOD._TimerService:ClearTimer(completionTimer)
                return
              end
              if not animationSprite.firstAnimationEnded then
                return
              end
              ___MOD._TimerService:ClearTimer(completionTimer)
              self:completeSecretLibraryDirection()
            end, 0.05)
          end
          animationSprite:setWzSprite(animation, false)
        end, start)
      end
    end
  end
end

